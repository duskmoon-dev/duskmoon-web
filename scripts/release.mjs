import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  copyFileSync, existsSync, globSync, lstatSync, mkdirSync, readFileSync, writeFileSync,
} from "node:fs";
import { basename, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { setTimeout as delay } from "node:timers/promises";

const root = fileURLToPath(new URL("../", import.meta.url));
const inventory = readJson(join(root, "docs/package-inventory.json")).packages;
const version = readFileSync(join(root, "VERSION"), "utf8").trim();
assert.match(version, /^\d+\.\d+\.\d+$/, "VERSION must be a stable release");
const npmInventory = inventory.filter(({ registry }) => registry === "npm");
const group = new Set(npmInventory.map(({ name }) => name));
const hex = inventory.find(({ registry }) => registry === "hex");
const dependencyFields = ["dependencies", "peerDependencies", "optionalDependencies", "devDependencies"];
const npmRegistry = "https://registry.npmjs.org";
const hexApi = "https://hex.pm/api";
const hexTarballs = "https://repo.hex.pm/tarballs";
const propagating = Symbol("registry metadata exists");
const standaloneFiles = ["duskmoonui.js", "duskmoonui.mjs", "duskmoonui.css", "duskmoonui-themes.css"];
const repository = "git+https://github.com/duskmoon-dev/duskmoon-web.git";
const reactVersionFile = join(root, "packages/react/components/src/generated/version.ts");
const reactVersionSource =
  `// This file is generated by scripts/sync-version.ts.
export const version = "${version}";
`;

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function run(command, args, cwd = root) {
  return execFileSync(command, args, { cwd, encoding: "utf8", maxBuffer: 20 * 1024 * 1024 });
}

function digest(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function id({ registry, name }) {
  return `${registry}:${name}`;
}

function requirementEntries(manifest) {
  return dependencyFields.flatMap((field) => Object.entries(manifest[field] ?? {}));
}

function manifests() {
  assert.equal(group.size, npmInventory.length, "Duplicate npm inventory entry");
  assert.equal(inventory.length, npmInventory.length + 1, "Expected one Hex package");
  const workspacePatterns = readJson(join(root, "package.json")).workspaces;
  const publicManifests = new Set(globSync(workspacePatterns.map((p) => p + "/package.json"), { cwd: root })
    .filter((path) => !readJson(join(root, path)).private));
  const packages = new Map(npmInventory.map((entry) => {
    const path = join(entry.path, "package.json");
    assert(publicManifests.delete(path), `Missing public workspace ${path}`);
    const manifest = readJson(join(root, path));
    assert.equal(manifest.name, entry.name, path);
    return [entry.name, manifest];
  }));
  assert.equal(publicManifests.size, 0, `Missing release inventory: ${[...publicManifests].join(", ")}`);
  return packages;
}

function sync() {
  const packages = manifests();
  for (const entry of npmInventory) {
    const manifest = packages.get(entry.name);
    manifest.version = version;
    manifest.repository = { type: "git", url: repository, directory: entry.path };
    for (const field of dependencyFields) {
      for (const dependency of Object.keys(manifest[field] ?? {})) {
        if (group.has(dependency)) manifest[field][dependency] = version;
      }
    }
    writeFileSync(join(root, entry.path, "package.json"), JSON.stringify(manifest, null, 2) + "\n");
  }
  writeFileSync(join(root, hex.path, "VERSION"), version + "\n");
  writeFileSync(reactVersionFile, reactVersionSource);
}

function validateManifest(manifest, name, { shipped = false } = {}) {
  assert.equal(manifest.name, name);
  assert.equal(manifest.version, version, name);
  for (const [dep, range] of requirementEntries(manifest)) {
    if (group.has(dep)) assert.equal(range, version, `${name} -> ${dep}`);
    if (shipped) assert(!/^(workspace|file|link):/.test(range), `${name} ships a local reference to ${dep}`);
  }
}

function publicationOrder() {
  const packages = manifests();
  for (const entry of npmInventory) {
    const manifest = packages.get(entry.name);
    validateManifest(manifest, entry.name);
    assert.equal(manifest.repository?.url, repository, entry.name);
    assert.equal(manifest.repository?.directory, entry.path, entry.name);
  }
  assert.equal(readFileSync(join(root, hex.path, "VERSION"), "utf8").trim(), version);
  assert.equal(readFileSync(reactVersionFile, "utf8"), reactVersionSource);
  const byName = new Map(npmInventory.map((entry) => [entry.name, entry]));
  const pending = new Set();
  const added = new Set();
  const order = [];

  function visit(name) {
    if (added.has(name)) return;
    assert(!pending.has(name), `Published package dependency cycle: ${[...pending, name].join(" -> ")}`);
    pending.add(name);
    const { devDependencies: _, ...runtime } = packages.get(name);
    const edges = requirementEntries(runtime).map(([dependency]) => dependency);
    for (const dep of [...new Set(edges)].filter((dep) => group.has(dep)).sort()) visit(dep);
    pending.delete(name);
    added.add(name);
    order.push(byName.get(name));
  }

  for (const name of [...group].sort()) visit(name);
  return [...order, hex];
}

function checkedSource(sha) {
  assert.match(sha, /^[0-9a-f]{40}$/, "Use a full Git commit SHA");
  assert.equal(run("git", ["rev-parse", "HEAD"]).trim(), sha);
  assert.equal(run("git", ["status", "--porcelain"]).trim(), "", "Release requires a clean source tree");
}

function artifactFile({ registry, name }) {
  return registry === "npm"
    ? `${name.replace(/^@/, "").replace("/", "-")}-${version}.tgz`
    : `${name}-${version}.tar`;
}

function auditNpm(path, name) {
  const manifest = JSON.parse(run("tar", ["-xOf", path, "package/package.json"]));
  validateManifest(manifest, name, { shipped: true });
  const files = new Set(run("tar", ["-tf", path]).trim().split("\n").map((p) => p.replace(/^package\//, "")));

  function verifyTargets(target) {
    if (target == null) return;
    if (typeof target !== "string") {
      for (const child of Object.values(target)) verifyTargets(child);
      return;
    }
    const entry = target.replace(/^\.\//, "");
    const wildcard = entry.split("*").map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join(".+");
    assert(entry.includes("*") ? [...files].some((p) => new RegExp(`^${wildcard}$`).test(p)) : files.has(entry),
      `${name} has missing packed target ${target}`);
  }

  verifyTargets(manifest.exports);
  for (const field of ["main", "module", "style", "types"]) verifyTargets(manifest[field]);
}

function auditHex(path) {
  const metadata = run("tar", ["-xOf", path, "metadata.config"]);
  assert(metadata.includes(`{<<"name">>,<<"${hex.name}">>}`), "Wrong Hex package name");
  assert(metadata.includes(`{<<"app">>,<<"${hex.name}">>}`), "Wrong OTP application");
  assert(metadata.includes(`{<<"version">>,<<"${version}">>}`), "Wrong Hex package version");
  for (const file of ["VERSION", "LICENSE", "mix.exs", "priv/static", "lib/duskmoon_phoenix"]) {
    assert(metadata.includes(`<<"${file}`) || metadata.includes(`<<"${file}/`),
      `Hex metadata missing ${file}`);
  }
}

function fileMetadata(path) {
  const info = lstatSync(path);
  assert(info.isFile() && info.size > 0, `Expected nonempty regular artifact ${path}`);
  return { file: basename(path), bytes: info.size, sha256: digest(readFileSync(path)) };
}

function readArtifact(path, entry) {
  if (entry.registry === "npm") auditNpm(path, entry.name);
  else auditHex(path);
  return { name: entry.name, registry: entry.registry, version, ...fileMetadata(path) };
}

function stage(dir, sha, hexPath) {
  checkedSource(sha);
  const order = publicationOrder();
  assert(!existsSync(dir), `Output directory already exists: ${dir}`);
  mkdirSync(dir, { recursive: true });
  const artifacts = order.map((entry) => {
    const path = join(dir, artifactFile(entry));
    if (entry.registry === "hex") {
      copyFileSync(hexPath, path);
    } else {
      const output = JSON.parse(run("npm", [
        "pack", "--json", "--ignore-scripts", "--pack-destination", dir,
      ], join(root, entry.path)));
      assert.equal(output[0]?.filename, basename(path), id(entry));
    }
    return readArtifact(path, entry);
  });
  const locks = ["bun.lock", "phoenix/mix.lock"].map((file) => ({
    file,
    sha256: digest(readFileSync(join(root, file))),
  }));
  const assets = standaloneFiles.map((file) => {
    const path = join(dir, file);
    copyFileSync(join(root, "packages/css/core/dist/standalone", file), path);
    return fileMetadata(path);
  });
  writeFileSync(join(dir, "release.json"), JSON.stringify({ version, sha, locks, artifacts, assets }, null, 2) + "\n");
  console.log(`Staged ${artifacts.length} distributions for ${version} at ${sha}`);
}

function verify(dir, sha) {
  checkedSource(sha);
  const manifest = readJson(join(dir, "release.json"));
  assert.equal(manifest.sha, sha);
  assert.equal(manifest.version, version);
  assert.deepEqual(manifest.locks, ["bun.lock", "phoenix/mix.lock"].map((file) => ({
    file,
    sha256: digest(readFileSync(join(root, file))),
  })));
  const actual = publicationOrder().map((entry) => readArtifact(join(dir, artifactFile(entry)), entry));
  assert.deepEqual(manifest.artifacts, actual, "Immutable artifact bytes, metadata, or order differ");
  assert.deepEqual(manifest.assets, standaloneFiles.map((file) => fileMetadata(join(dir, file))));
  return actual;
}

async function reconcile(artifacts, registry) {
  for (const artifact of artifacts) {
    const found = await registry.lookup(artifact);
    const publishedHash = found === propagating ? await registry.confirm(artifact) : found;
    assert(found !== propagating || publishedHash !== null, `Existing artifact is still propagating: ${id(artifact)}`);
    if (publishedHash === null) {
      await registry.publish(artifact);
    } else {
      assert.equal(publishedHash, artifact.sha256, `Published bytes differ for ${id(artifact)}`);
      console.log(`Reusing ${id(artifact)}@${artifact.version}`);
    }
  }
  // Read-only propagation retries. A missing read never triggers another write.
  for (let position = 0; position < artifacts.length; position += 8) {
    await Promise.all(artifacts.slice(position, position + 8).map(async (artifact) => {
      const published = await registry.confirm(artifact);
      assert.equal(published, artifact.sha256, `Registry verification failed for ${id(artifact)}`);
    }));
  }
}

async function get(url) {
  return fetch(url, { signal: AbortSignal.timeout(30_000) });
}

function realRegistry(dir) {
  async function lookup(artifact) {
    const { name, registry, version } = artifact;
    const root = registry === "npm"
      ? `${npmRegistry}/${encodeURIComponent(name)}/${version}`
      : `${hexApi}/packages/${name}/releases/${version}`;
    const response = await get(root);
    if (response.status === 404) return null;
    assert(response.ok, `Lookup ${id(artifact)} returned HTTP ${response.status}`);
    const metadata = await response.json();
    assert.equal(metadata.version, version, id(artifact));
    const url = registry === "npm" ? metadata.dist.tarball : `${hexTarballs}/${artifact.file}`;
    assert.equal(new URL(url).origin, registry === "npm" ? npmRegistry : "https://repo.hex.pm");
    const tar = await get(url);
    if (tar.status === 404) return propagating;
    assert(tar.ok, `Artifact download for ${id(artifact)} returned HTTP ${tar.status}`);
    return digest(Buffer.from(await tar.arrayBuffer()));
  }

  return {
    lookup,
    async publish(artifact) {
      const file = join(dir, artifact.file);
      console.log(`Publishing ${id(artifact)}@${artifact.version}`);
      assert.equal(digest(readFileSync(file)), artifact.sha256);
      if (artifact.registry === "npm") {
        console.log(run("npm", ["publish", file, "--registry", npmRegistry, "--access", "public",
          "--provenance", "--ignore-scripts"]).trim());
      } else {
        assert(process.env.HEX_API_KEY, "HEX_API_KEY is required for Hex publication");
        const response = await fetch(`${hexApi}/packages/${artifact.name}/releases?replace=false`, {
          method: "POST",
          headers: { authorization: process.env.HEX_API_KEY, "content-type": "application/octet-stream" },
          body: readFileSync(file),
          redirect: "error",
          signal: AbortSignal.timeout(60_000),
        });
        assert(response.ok, `Hex upload returned HTTP ${response.status}`);
      }
    },
    async confirm(artifact) {
      for (let attempt = 0; attempt < 120; attempt++) {
        let hash;
        try {
          hash = await lookup(artifact);
        } catch (error) {
          if (attempt === 119) throw error;
        }
        if (typeof hash === "string") return hash;
        await delay(5000);
      }
      return null;
    },
  };
}

async function dryRun(artifacts) {
  const simulated = new Map();
  const writes = [];
  const cutoff = Math.floor(artifacts.length / 2);
  const interruption = new Error("simulated interrupted publication");
  let interrupt = true;
  const lookup = async (artifact) => simulated.get(id(artifact)) ?? null;
  const registry = {
    lookup,
    confirm: lookup,
    async publish(artifact) {
      assert(!simulated.has(id(artifact)), `Duplicate publication: ${id(artifact)}`);
      simulated.set(id(artifact), artifact.sha256);
      writes.push(id(artifact));
      if (interrupt && writes.length === cutoff) throw interruption;
    },
  };
  await assert.rejects(reconcile(artifacts, registry), interruption);
  assert.equal(writes.length, cutoff);
  interrupt = false;
  await reconcile(artifacts, registry);
  assert.deepEqual(writes, artifacts.map(id), "Resume changed publication order");
  simulated.set(id(artifacts[0]), "unexpected hash");
  await assert.rejects(reconcile(artifacts, registry), /Published bytes differ/);
  assert.equal(writes.length, artifacts.length);
  console.log(`Dry-run passed for all ${writes.length} artifacts, including interrupted resume and hash conflict`);
}

const [command, output, sha, hexInput] = process.argv.slice(2);
if (command === "version") {
  console.log(version);
} else if (command === "sync") {
  sync();
} else if (command === "check") {
  const order = publicationOrder();
  console.log(`${version}: ${order.length} distributions\n${order.map(id).join("\n")}`);
} else if (command === "stage" && output && sha && hexInput) {
  stage(resolve(output), sha, resolve(hexInput));
} else if (["verify", "dry-run", "publish"].includes(command) && output && sha) {
  const dir = resolve(output);
  const artifacts = verify(dir, sha);
  if (command === "dry-run") await dryRun(artifacts);
  if (command === "publish") await reconcile(artifacts, realRegistry(dir));
  console.log(`${command} verified ${artifacts.length} distributions for ${version}`);
} else {
  throw new Error("Usage: release.mjs version|sync|check | stage OUTPUT SHA HEX_TAR | verify|dry-run|publish OUTPUT SHA");
}
